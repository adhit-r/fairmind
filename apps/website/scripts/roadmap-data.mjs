// Writes src/lib/roadmap-activity.ts from git history: commits on main per month, and how many name Claude as a
// co-author. Run from apps/website before a release (node scripts/roadmap-data.mjs); the roadmap page reads the file,
// because Netlify's build may not have the full history.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const ref = process.argv[2] || 'origin/main';
const months = {};
for (const m of git('log', '--format=%ad', '--date=format:%Y-%m', ref).split('\n').filter(Boolean)) months[m] = (months[m] ?? 0) + 1;
const claude = git('log', '--format=%(trailers:key=Co-Authored-By,valueonly)%x00', ref).split('\0').filter((t) => /Claude/i.test(t)).length;
const total = Number(git('rev-list', '--count', ref).trim());
const first = git('log', '--reverse', '--format=%ad', '--date=short', ref).split('\n')[0];
const out = { generatedAt: new Date().toISOString().slice(0, 10), firstCommit: first, totalCommits: total, claudeCommits: claude,
  months: Object.fromEntries(Object.entries(months).sort()) };
writeFileSync(new URL('../src/lib/roadmap-activity.ts', import.meta.url),
  `// Generated by scripts/roadmap-data.mjs from git history; run it again to refresh.\nexport default ${JSON.stringify(out, null, 2)};\n`);
console.log(`roadmap-activity.ts: ${total} commits, ${claude} with Claude, ${Object.keys(months).length} months`);
